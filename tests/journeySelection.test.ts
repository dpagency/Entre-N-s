function memory() {
  const values = new Map<string, string>();
  return { getItem: (k: string) => values.get(k) ?? null, setItem: (k: string, v: string) => { values.set(k, v); } };
}
test('initial accordion is generated by the catalog with collapsed complementary information', () => {
  const html = renderToStaticMarkup(React.createElement(JourneyHome));
  assert.equal((html.match(/data-journey="/g) || []).length, JOURNEYS.length);
  assert.equal((html.match(/aria-expanded="true"/g) || []).length, 0);
  assert(html.includes('aria-controls='));
  assert(html.indexOf('data-start-journey') < html.indexOf('role="region"'), 'Start must remain outside the collapsible panel');
  assert(html.includes(APPROVED_CITY_ARTWORK));
  assert(html.includes('Em desenvolvimento'));
  assert(html.includes('Quando alguém procura você'));
  assert.equal((html.match(/data-start-journey=/g) || []).length, 1);
  assert(!html.includes('Conhecer o Guia Lilás'));
});

test('approved artwork is active while unapproved or absent alternatives retain the original', () => {
  assert.equal(cityArtworkSource(), APPROVED_CITY_ARTWORK);
  assert.notEqual(APPROVED_CITY_ARTWORK, ORIGINAL_CITY_ARTWORK);
  assert.equal(cityArtworkSource({ original: 'original', alternative: 'updated', approved: false }), 'original');
  assert.equal(cityArtworkSource({ original: 'original', alternative: 'updated', approved: true }), 'updated');
  assert.equal(cityArtworkSource({ original: 'original', alternative: null, approved: true }), 'original');
});

test('adding a catalog entry automatically extends the accordion without another illustration', () => {
  const catalog = JOURNEYS as JourneyDefinition[];
  const count = catalog.length;
  catalog.push({ id: 'test-only-catalog-entry', title: 'Fixture', description: 'Fixture', version: 1, status: 'editorial-review', missionIds: [] });
  try {
    const html = renderToStaticMarkup(React.createElement(JourneyHome));
    assert.equal((html.match(/data-journey="/g) || []).length, count + 1);
    assert(html.includes('data-journey="test-only-catalog-entry"'));
    assert.equal((html.match(/<img /g) || []).length, 1);
  } finally { catalog.pop(); }
});

test('completion resources require editorial approval, all missions and a completed journey', () => {
  const draft = JOURNEYS[1];
  assert.equal(draft.missionIds.length, 0);
  assert.equal(draft.plannedMissions?.length, 4);
  const definition: JourneyDefinition = { ...draft, status: 'available', missionIds: ['fixture-only'],
    presentation: { resources: draft.presentation!.resources!.map(r => ({ ...r, editorialStatus: 'approved' })) } };
  const state = { journeyDefinitionId: draft.id, phase: 'GAME_SUMMARY' as const, completedMissionIds: ['fixture-only'] };
  assert.equal(completedJourneyResources(state).length, 0);
  assert.equal(completedJourneyResources(state, definition)[0].label, 'Conhecer o Guia Lilás');
  assert.equal(completedJourneyResources({ ...state, completedMissionIds: [] }, definition).length, 0);
  assert.equal(completedJourneyResources({ ...state, phase: 'BOARD_SELECT' }, definition).length, 0);
  assert.equal(completedJourneyResources(state, { ...definition, status: 'editorial-review' }).length, 0);
  assert.equal(completedJourneyResources(state, { ...definition, presentation: { resources: [{ id: 'unsafe', label: 'Test', url: 'javascript:alert(1)', editorialStatus: 'approved' }] } }).length, 0);
  assert.equal(renderToStaticMarkup(React.createElement(JourneyResources, { state: state as any })), '');
});

test('selection prefers the active attempt and keeps other attempts independently resumable', () => {
  restore({ rooms: [], tokens: [], evaluations: [], feedback: [] });
  const storage = memory();
  const connection = { readyState: 1, send: (_: string) => {} };
  handleClientMessage(connection, { type: 'CREATE_ROOM', pilotVersion: 2, nickname: 'Teste', characterId: 'alex', variantIndex: 0 });
  handleClientMessage(connection, { type: 'START_GAME' });
  const first = structuredClone(snapshot());
  archiveSnapshot(storage, first);
  const second = structuredClone(first);
  second.rooms[0][1].journeyId = 'fixture-second';
  second.rooms[0][1].completedMissionIds = ['missao-1'];
  archiveSnapshot(storage, second);
  storage.setItem('entre-nos-solo', JSON.stringify(first));
  storage.setItem('guardioes_room_code', first.rooms[0][0]);
  const attempts = savedJourneyAttempts(storage, ORIGINAL_JOURNEY_ID);
  assert.equal(attempts.length, 2);
  assert.equal(attempts[0].attempt, first.rooms[0][1].journeyId);
  assert.deepEqual(loadAttempt(storage, ORIGINAL_JOURNEY_ID, 'fixture-second')!.snapshot.rooms[0][1].completedMissionIds, ['missao-1']);
  assert.equal(savedJourneyAttempts(storage, JOURNEYS[1].id).length, 0);
});

test('legacy lobby saves remain resumable until their started attempt replaces the preparation checkpoint', () => {
  restore({ rooms: [], tokens: [], evaluations: [], feedback: [] });
  const storage = memory();
  const connection = { readyState: 1, send: (_: string) => {} };
  handleClientMessage(connection, { type: 'CREATE_ROOM', pilotVersion: 2, nickname: 'Teste', characterId: 'alex', variantIndex: 1 });
  const lobby = structuredClone(snapshot());
  storage.setItem('entre-nos-solo', JSON.stringify(lobby));
  assert.equal(savedJourneyAttempts(storage, ORIGINAL_JOURNEY_ID)[0].snapshot.rooms[0][1].phase, 'LOBBY');
  handleClientMessage(connection, { type: 'START_GAME' });
  const started = snapshot();
  storage.setItem('entre-nos-solo', JSON.stringify(started));
  const attempts = savedJourneyAttempts(storage, ORIGINAL_JOURNEY_ID);
  assert.equal(attempts.length, 1);
  assert.equal(attempts[0].attempt, started.rooms[0][1].journeyId);
});
